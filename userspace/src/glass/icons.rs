#[inline]
pub const fn icon_for_app(app: AppId) -> &'static Icon16 {
    match app {
        AppId::Terminal => &ICON_TERMINAL,
        AppId::LifeStation => &ICON_LIFESTATION,
        AppId::Files => &ICON_FILES,
        AppId::Settings => &ICON_SETTINGS,
        AppId::Editor => &ICON_EDITOR,
        AppId::Calculator => &ICON_CALC,
    }
}

/// Blit a `16x16` two-tone icon onto `buf` clipped to `clip`.
/// # Safety
/// `buf` must cover `buf_w * buf_h` `u32` pixels.
#[allow(clippy::too_many_arguments)]
pub unsafe fn draw_icon16(
    buf: *mut u32,
    buf_w: usize,
    buf_h: usize,
    x: usize,
    y: usize,
    icon: &Icon16,
    fg: u32,
    accent: u32,
    clip: Rect,
) {
    let inter = Rect::new(x, y, 16, 16).intersect(clip).clamp_to(buf_w, buf_h);
    if inter.is_empty() {
        return;
    }
    for py in inter.y..(inter.y + inter.h) {
        let ry = py - y;
        let pm = icon.primary[ry];
        let am = icon.accent[ry];
        let row_off = py * buf_w;
        for px in inter.x..(inter.x + inter.w) {
            let bit = 0x8000u16 >> (px - x);
            if (am & bit) != 0 {
                unsafe { *buf.add(row_off + px) = accent };
            } else if (pm & bit) != 0 {
                unsafe { *buf.add(row_off + px) = fg };
            }
        }
    }
}
