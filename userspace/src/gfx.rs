//! Ring 3 Desktop Foundation Geometry, `DirtyRegion` Tracker, and Full Printable ASCII 8x16 Font.
//!
//! Zero UI or rasterization logic resides in `dry-kernel`: `Rect`, `DirtyRegion`, and glyph
//! tables live purely in `no_std` userspace (`dry-display` compositor).

pub const BOX_HORIZ: u8 = 0x80;

/// Axis-aligned pixel rectangle (`x, y` top-left, `w, h` dimensions).
#[repr(C)]
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Rect {
    pub x: usize,
    pub y: usize,
    pub w: usize,
    pub h: usize,
}

impl Rect {
    pub const EMPTY: Self = Self {
        x: 0,
        y: 0,
        w: 0,
        h: 0,
    };

    #[inline]
    pub const fn new(x: usize, y: usize, w: usize, h: usize) -> Self {
        Self { x, y, w, h }
    }

    #[inline]
    pub const fn is_empty(self) -> bool {
        self.w == 0 || self.h == 0
    }

    #[inline]
    pub fn clamp_to(self, max_w: usize, max_h: usize) -> Self {
        if self.is_empty() || self.x >= max_w || self.y >= max_h {
            return Self::EMPTY;
        }
        let x2 = (self.x + self.w).min(max_w);
        let y2 = (self.y + self.h).min(max_h);
        Self {
            x: self.x,
            y: self.y,
            w: x2.saturating_sub(self.x),
            h: y2.saturating_sub(self.y),
        }
    }

    #[inline]
    pub fn intersect(self, other: Self) -> Self {
        if self.is_empty() || other.is_empty() {
            return Self::EMPTY;
        }
        let x1 = self.x.max(other.x);
        let y1 = self.y.max(other.y);
        let x2 = (self.x + self.w).min(other.x + other.w);
        let y2 = (self.y + self.h).min(other.y + other.h);
        if x2 <= x1 || y2 <= y1 {
            Self::EMPTY
        } else {
            Self {
                x: x1,
                y: y1,
                w: x2 - x1,
                h: y2 - y1,
            }
        }
    }

    #[inline]
    pub fn union(self, other: Self) -> Self {
        if self.is_empty() {
            return other;
        }
        if other.is_empty() {
            return self;
        }
        let x1 = self.x.min(other.x);
        let y1 = self.y.min(other.y);
        let x2 = (self.x + self.w).max(other.x + other.w);
        let y2 = (self.y + self.h).max(other.y + other.h);
        Self {
            x: x1,
            y: y1,
            w: x2 - x1,
            h: y2 - y1,
        }
    }
}

/// Accumulates damaged screen regions between `IPC_OP_SURFACE_PRESENT` / `MOVE` frames so only
/// modified scanlines are copied across PCIe/MMIO into the uncached/WC GOP framebuffer.
#[derive(Clone, Copy, Debug, Default)]
pub struct DirtyRegion {
    bounds: Rect,
}

impl DirtyRegion {
    pub const fn new() -> Self {
        Self {
            bounds: Rect::EMPTY,
        }
    }

    #[inline]
    pub fn mark(&mut self, r: Rect) {
        self.bounds = self.bounds.union(r);
    }

    #[inline]
    pub fn take(&mut self, fb_w: usize, fb_h: usize) -> Option<Rect> {
        let clamped = self.bounds.clamp_to(fb_w, fb_h);
        self.bounds = Rect::EMPTY;
        if clamped.is_empty() {
            None
        } else {
            Some(clamped)
        }
    }
}

